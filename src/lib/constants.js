export function toSportDbValue(sport) {
  if (!sport) return 'other'
  const raw = String(sport).trim()
  if (SPORT_DB_VALUES[raw]) return SPORT_DB_VALUES[raw]
  const s = raw.toLowerCase()
  if (SPORT_DB_VALUES[s]) return SPORT_DB_VALUES[s]
  if (VALID_SPORT_ENUMS.includes(s)) return s

  if (s.includes('fuss') || s.includes('fuß') || s.includes('foot') || s.includes('soccer') || s.includes('bolzen') || s.includes('kicken')) {
    return 'football'
  }
  if (s.includes('basket') || s.includes('bball')) {
    return 'basketball'
  }
  if (s.includes('voll') || s.includes('beach')) {
    return 'volleyball'
  }
  if (s.includes('tischtennis') || s.includes('ping') || s.includes('table')) {
    return 'table_tennis'
  }
  if (s.includes('tennis')) {
    return 'tennis'
  }
  if (s.includes('padel')) {
    return 'padel'
  }
  if (s.includes('lauf') || s.includes('jogg') || s.includes('run')) {
    return 'running'
  }
  if (s.includes('rad') || s.includes('bike') || s.includes('cycl')) {
    return 'cycling'
  }
  if (s.includes('badminton') || s.includes('federball')) {
    return 'badminton'
  }

  // Any other sport or free text (e.g. "Spazieren", "Chillen", "Gym", "Yoga", "Bouldern")
  // maps safely to 'other' so Postgres enum constraint is never violated
  return 'other'
}

/**
 * Intelligently resolves sport key, display label, emoji, illustration, and image
 * from a session object or raw sport string, including checking session.title and session.description.
 */
export function resolveSessionSportInfo(sessionOrSport = '', optTitle = '', optDescription = '') {
  let rawSport = ''
  let title = optTitle || ''
  let description = optDescription || ''

  if (typeof sessionOrSport === 'object' && sessionOrSport !== null) {
    rawSport = sessionOrSport.sport || ''
    title = sessionOrSport.title || title || ''
    description = sessionOrSport.description || description || ''
  } else {
    rawSport = String(sessionOrSport || '')
  }

  // Check if description contains an embedded custom activity note:
  // e.g. "Universität: Campus | Aktivität: Spazieren"
  let customActivity = null
  if (description) {
    const actMatch = description.match(/Aktivität:\s*([^|\n\r]+)/i)
    if (actMatch && actMatch[1]) {
      customActivity = actMatch[1].trim()
    }
  }

  const termsToCheck = [
    customActivity,
    rawSport && rawSport !== 'other' && rawSport !== 'Sonstiges' ? rawSport : null,
    title,
    rawSport,
  ].filter(Boolean).map(t => String(t).toLowerCase())

  const combined = termsToCheck.join(' ')

  // 1. Spazieren / Walk / Gehen / Wandern
  if (
    combined.includes('spazier') ||
    combined.includes('walk') ||
    combined.includes('wander') ||
    combined.includes('gehen') ||
    combined.includes('promenade') ||
    combined.includes('schlendern')
  ) {
    const rawLabel = customActivity || (title.toLowerCase().includes('spazier') ? 'Spazieren' : 'Spazieren')
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'walking',
      label,
      emoji: '🚶',
      illustration: SPORT_ILLUSTRATIONS.walking,
      image: SPORT_IMAGES.Spazieren,
      isBar: false,
    }
  }

  // 2. Running / Laufen / Joggen
  if (
    combined.includes('lauf') ||
    combined.includes('jogg') ||
    combined.includes('running') ||
    combined.includes('marathon') ||
    combined.includes('sprint')
  ) {
    const rawLabel = customActivity || 'Laufen'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'running',
      label,
      emoji: '🏃',
      illustration: SPORT_ILLUSTRATIONS.running,
      image: SPORT_IMAGES.Laufen,
      isBar: false,
    }
  }

  // 3. Cycling / Radfahren
  if (
    combined.includes('rad') ||
    combined.includes('bike') ||
    combined.includes('biken') ||
    combined.includes('cycl') ||
    combined.includes('rennrad')
  ) {
    const rawLabel = customActivity || 'Radfahren'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'cycling',
      label,
      emoji: '🚴',
      illustration: SPORT_ILLUSTRATIONS.cycling,
      image: SPORT_IMAGES.Radfahren,
      isBar: false,
    }
  }

  // 4. Tennis & Padel
  if (combined.includes('padel')) {
    return {
      key: 'padel',
      label: 'Padel',
      emoji: '🎾',
      illustration: SPORT_ILLUSTRATIONS.tennis,
      image: SPORT_IMAGES.Tennis,
      isBar: false,
    }
  }
  if (combined.includes('tennis') && !combined.includes('tischtennis')) {
    return {
      key: 'tennis',
      label: 'Tennis',
      emoji: '🎾',
      illustration: SPORT_ILLUSTRATIONS.tennis,
      image: SPORT_IMAGES.Tennis,
      isBar: false,
    }
  }

  // 5. Table Tennis / Tischtennis / Ping Pong
  if (combined.includes('tischtennis') || combined.includes('ping') || combined.includes('table_tennis')) {
    return {
      key: 'table_tennis',
      label: 'Tischtennis',
      emoji: '🏓',
      illustration: SPORT_ILLUSTRATIONS.table_tennis,
      image: SPORT_IMAGES.Tischtennis,
      isBar: false,
    }
  }

  // 6. Basketball / Streetball
  if (combined.includes('basket') || combined.includes('bball') || combined.includes('streetball')) {
    return {
      key: 'basketball',
      label: 'Basketball',
      emoji: '🏀',
      illustration: SPORT_ILLUSTRATIONS.basketball,
      image: SPORT_IMAGES.Basketball,
      isBar: false,
    }
  }

  // 7. Volleyball / Beachvolleyball
  if (combined.includes('voll') || combined.includes('beach')) {
    return {
      key: 'volleyball',
      label: 'Volleyball',
      emoji: '🏐',
      illustration: SPORT_ILLUSTRATIONS.volleyball,
      image: SPORT_IMAGES.Volleyball,
      isBar: false,
    }
  }

  // 8. Football / Fußball / Soccer / Bolzen / Kicken / Futsal
  if (
    combined.includes('fuss') ||
    combined.includes('fuß') ||
    combined.includes('foot') ||
    combined.includes('soccer') ||
    combined.includes('bolzen') ||
    combined.includes('kicken') ||
    combined.includes('futsal')
  ) {
    return {
      key: 'football',
      label: 'Fußball',
      emoji: '⚽',
      illustration: SPORT_ILLUSTRATIONS.football,
      image: SPORT_IMAGES.Fußball,
      isBar: false,
    }
  }

  // 9. Fitness / Gym / Workout / Calisthenics
  if (
    combined.includes('fitness') ||
    combined.includes('gym') ||
    combined.includes('workout') ||
    combined.includes('kraft') ||
    combined.includes('calisthenic') ||
    combined.includes('pumpen')
  ) {
    const rawLabel = customActivity || 'Fitness'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'fitness',
      label,
      emoji: '💪',
      illustration: SPORT_ILLUSTRATIONS.fitness,
      image: SPORT_IMAGES.Fitness,
      isBar: false,
    }
  }

  // 10. Yoga / Pilates / Meditation / Stretching
  if (
    combined.includes('yoga') ||
    combined.includes('pilates') ||
    combined.includes('stretch') ||
    combined.includes('meditat')
  ) {
    const rawLabel = customActivity || 'Yoga'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'yoga',
      label,
      emoji: '🧘',
      illustration: SPORT_ILLUSTRATIONS.yoga,
      image: SPORT_IMAGES.Yoga,
      isBar: false,
    }
  }

  // 11. Swimming / Schwimmen
  if (combined.includes('schwimm') || combined.includes('swim')) {
    const rawLabel = customActivity || 'Schwimmen'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'swimming',
      label,
      emoji: '🏊',
      illustration: SPORT_ILLUSTRATIONS.swimming,
      image: SPORT_ILLUSTRATIONS.swimming,
      isBar: false,
    }
  }

  // 12. Skating / Skateboard
  if (combined.includes('skat') || (combined.includes('board') && !combined.includes('snowboard'))) {
    const rawLabel = customActivity || 'Skating'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'skating',
      label,
      emoji: '🛹',
      illustration: SPORT_ILLUSTRATIONS.skating,
      image: SPORT_IMAGES.Sonstiges,
      isBar: false,
    }
  }

  // 13. Snowboard / Wintersport / Ski
  if (combined.includes('snow') || combined.includes('ski') || combined.includes('winter')) {
    const rawLabel = customActivity || 'Wintersport'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'snowboard',
      label,
      emoji: '🏂',
      illustration: SPORT_ILLUSTRATIONS.snowboard,
      image: SPORT_IMAGES.Sonstiges,
      isBar: false,
    }
  }

  // 14. Horse / Reiten
  if (combined.includes('reit') || combined.includes('horse') || combined.includes('pferd')) {
    const rawLabel = customActivity || 'Reiten'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'horse',
      label,
      emoji: '🏇',
      illustration: SPORT_ILLUSTRATIONS.horse,
      image: SPORT_IMAGES.Sonstiges,
      isBar: false,
    }
  }

  // 15. Spikeball / Roundnet
  if (combined.includes('spike') || combined.includes('roundnet')) {
    return {
      key: 'spikeball',
      label: 'Spikeball',
      emoji: '🟡',
      illustration: SPORT_ILLUSTRATIONS.spikeball,
      image: SPORT_IMAGES.Sonstiges,
      isBar: false,
    }
  }

  // 16. Badminton / Federball
  if (combined.includes('badminton') || combined.includes('federball')) {
    return {
      key: 'badminton',
      label: 'Badminton',
      emoji: '🏸',
      illustration: SPORT_ILLUSTRATIONS.tennis,
      image: SPORT_IMAGES.Tennis,
      isBar: false,
    }
  }

  // 17. Climbing / Bouldern
  if (combined.includes('boulder') || combined.includes('kletter') || combined.includes('climb')) {
    const rawLabel = customActivity || 'Bouldern'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'climbing',
      label,
      emoji: '🧗',
      illustration: SPORT_ILLUSTRATIONS.fitness,
      image: SPORT_IMAGES.Sonstiges,
      isBar: false,
    }
  }

  // 18. Bar / Party / Drinks / Karaoke
  if (combined.includes('bar') || combined.includes('karaoke') || combined.includes('drink') || combined.includes('party')) {
    const rawLabel = customActivity || 'Bar'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'bar',
      label,
      emoji: '🍻',
      illustration: SPORT_ILLUSTRATIONS.bar,
      image: SPORT_ILLUSTRATIONS.bar,
      isBar: true,
    }
  }

  // 19. Chillen / Community / Meetup
  if (combined.includes('chill') || combined.includes('meet') || combined.includes('communit')) {
    const rawLabel = customActivity || 'Chillen'
    const label = rawLabel.charAt(0).toUpperCase() + rawLabel.slice(1)
    return {
      key: 'chillen',
      label,
      emoji: '😎',
      illustration: SPORT_ILLUSTRATIONS.chillen,
      image: SPORT_IMAGES.Chillen,
      isBar: false,
    }
  }

  // 20. Other / Sonstiges fallback (Friendly general sport illustration, NOT soccer!)
  const rawFallback = customActivity || (rawSport && rawSport !== 'other' && rawSport !== 'Sonstiges' ? rawSport : 'Sonstiges')
  const label = rawFallback.charAt(0).toUpperCase() + rawFallback.slice(1)
  return {
    key: 'other',
    label,
    emoji: SPORT_EMOJIS[label] || '🎯',
    illustration: SPORT_ILLUSTRATIONS.other,
    image: SPORT_IMAGES.Sonstiges,
    isBar: false,
  }
}

export function toSportLabel(sessionOrSport, optTitle = '', optDescription = '') {
  if (!sessionOrSport) return 'Sport'
  return resolveSessionSportInfo(sessionOrSport, optTitle, optDescription).label
}

export function getSportIllustration(sessionOrSport, optTitle = '', optDescription = '') {
  return resolveSessionSportInfo(sessionOrSport, optTitle, optDescription).illustration
}

export function toSkillDbValue(level) {
  if (!level) return 'intermediate'
  const l = String(level).trim().toLowerCase()
  if (l === 'beginner' || l === 'intermediate' || l === 'advanced') return l
  if (l.includes('anf') || l.includes('beg')) return 'beginner'
  if (l.includes('fort') || l.includes('adv') || l.includes('prof')) return 'advanced'
  return 'intermediate'
}

export function toSkillLabel(level) {
  return SKILL_LABELS[level] || level
}

